"""Windowed, self-contained Figure Studio launcher and loopback service.

PyInstaller places the bundled application in ``sys._MEIPASS / 'suite'``.
The editable workspace, local runtime descriptor and port live in the user's
data directory. No external Python executable or shell process is launched.
"""
from __future__ import annotations

import argparse
import hashlib
import http.client
import json
import logging
from logging.handlers import RotatingFileHandler
import os
from pathlib import Path
import secrets
import sys
import threading
import time
from http.server import ThreadingHTTPServer
from urllib.parse import urlsplit
import webbrowser


APP_ID = 'figure-studio-desktop-v1'
DEFAULT_PORT = 18767
PORT_ATTEMPTS = 20
STARTER = Path('desktop/resources/starter.html')
WINDOW_ICON = Path('desktop/resources/figure-studio.ico')
OFFICIAL_PROJECT_URL = 'https://github.com/zhoy0409-debug/polish-sci-figures'
WINDOW_TITLE = 'Figure Studio · polish-sci-figures'
LOG = logging.getLogger('figure-studio')


class LaunchError(RuntimeError):
    pass


def resource_root() -> Path:
    if getattr(sys, 'frozen', False):
        return Path(sys._MEIPASS) / 'suite'
    return Path(__file__).resolve().parents[1]


def default_data_dir() -> Path:
    base = os.environ.get('LOCALAPPDATA')
    if base:
        return Path(base) / 'Figure Studio'
    return Path.home() / '.local' / 'share' / 'Figure Studio'


def read_json(path: Path) -> dict:
    try:
        value = json.loads(path.read_text(encoding='utf-8'))
        return value if isinstance(value, dict) else {}
    except (OSError, ValueError):
        return {}


def write_json(path: Path, value: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + '.' + secrets.token_hex(6) + '.tmp')
    try:
        temporary.write_text(json.dumps(value, ensure_ascii=False, indent=2), encoding='utf-8')
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)


def prepare_runtime(data_dir: Path) -> None:
    data_dir.mkdir(parents=True, exist_ok=True)
    (data_dir / 'logs').mkdir(exist_ok=True)
    cache = data_dir / 'cache' / 'matplotlib'
    cache.mkdir(parents=True, exist_ok=True)
    os.environ['MPLCONFIGDIR'] = str(cache)
    os.environ['MPLBACKEND'] = 'Agg'
    # A --windowed executable has no stdout/stderr. Some numerical libraries
    # still write diagnostics there; give them a local sink instead of None.
    if sys.stdout is None or sys.stderr is None:
        stream = (data_dir / 'logs' / 'runtime.log').open('a', encoding='utf-8', buffering=1)
        if sys.stdout is None:
            sys.stdout = stream
        if sys.stderr is None:
            sys.stderr = stream
    if not LOG.handlers:
        handler = RotatingFileHandler(data_dir / 'logs' / 'launcher.log', maxBytes=1_000_000,
                                      backupCount=2, encoding='utf-8')
        handler.setFormatter(logging.Formatter('%(asctime)s %(levelname)s %(message)s'))
        LOG.addHandler(handler)
        LOG.setLevel(logging.INFO)


def prepare_workspace(data_dir: Path, suite_root: Path) -> Path:
    source = suite_root / STARTER
    if not source.is_file():
        raise LaunchError('安装文件不完整：缺少编辑器首页。请重新安装 Figure Studio。\n'
                          'The editor start page is missing. Reinstall Figure Studio.')
    raw = source.read_bytes()
    if b'</head>' not in raw or b'id="project"' not in raw:
        raise LaunchError('编辑器首页无效 / The bundled editor page is invalid.')
    workspace = data_dir / 'workspace'
    workspace.mkdir(parents=True, exist_ok=True)
    page = workspace / 'index.html'
    manifest_path = workspace / 'page.json'
    manifest = read_json(manifest_path)
    checksum = hashlib.sha256(raw).hexdigest()
    # Update only the page generated by this launcher. User-replaced HTML is
    # preserved. Browser projects and IndexedDB are separate from this shell.
    current = hashlib.sha256(page.read_bytes()).hexdigest() if page.exists() else None
    if current is None or current == manifest.get('sha256'):
        if current != checksum:
            temporary = workspace / 'index.html.new'
            temporary.write_bytes(raw)
            os.replace(temporary, page)
        write_json(manifest_path, {'sha256': checksum, 'app': APP_ID})
    return page


class InstanceLock:
    """OS-held lock: a crashed process releases it without stale PID guessing."""

    def __init__(self, path: Path):
        self.path = path
        self.file = None

    def acquire(self) -> bool:
        self.path.parent.mkdir(parents=True, exist_ok=True)
        handle = self.path.open('a+b')
        handle.seek(0, 2)
        if handle.tell() == 0:
            handle.write(b'0')
            handle.flush()
        handle.seek(0)
        try:
            if os.name == 'nt':
                import msvcrt
                msvcrt.locking(handle.fileno(), msvcrt.LK_NBLCK, 1)
            else:
                import fcntl
                fcntl.flock(handle.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
        except OSError:
            handle.close()
            return False
        self.file = handle
        return True

    def release(self) -> None:
        if self.file is None:
            return
        try:
            self.file.seek(0)
            if os.name == 'nt':
                import msvcrt
                msvcrt.locking(self.file.fileno(), msvcrt.LK_UNLCK, 1)
            else:
                import fcntl
                fcntl.flock(self.file.fileno(), fcntl.LOCK_UN)
        finally:
            self.file.close()
            self.file = None


def http_request(port: int, path: str = '/', payload=None, token: str | None = None,
                 instance_id: str | None = None, headers=None, timeout=180):
    connection = http.client.HTTPConnection('127.0.0.1', port, timeout=timeout)
    request_headers = dict(headers or {})
    body = None
    method = 'GET'
    if payload is not None:
        method = 'POST'
        body = json.dumps(payload, ensure_ascii=False, allow_nan=False).encode('utf-8')
        request_headers.setdefault('Content-Type', 'application/json')
        request_headers.setdefault('Origin', f'http://127.0.0.1:{port}')
    if token:
        request_headers['X-Studio-Token'] = token
    if instance_id:
        request_headers['X-Studio-Instance'] = instance_id
    try:
        connection.request(method, path, body=body, headers=request_headers)
        response = connection.getresponse()
        return response.status, response.read()
    finally:
        connection.close()


def probe_instance(record: dict) -> bool:
    port, identity = record.get('port'), record.get('instance_id')
    if record.get('app') != APP_ID or type(port) is not int or not 1024 <= port <= 65535:
        return False
    if not isinstance(identity, str) or not 20 <= len(identity) <= 128:
        return False
    try:
        status, raw = http_request(port, '/api/desktop/health', instance_id=identity, timeout=.8)
        result = json.loads(raw)
        return (status == 200 and isinstance(result, dict) and result.get('app') == APP_ID
                and result.get('instance_id') == identity)
    except (OSError, ValueError, http.client.HTTPException):
        return False


class ExistingInstance:
    def __init__(self, record):
        self.port = record['port']
        self.url = f'http://127.0.0.1:{self.port}/'


def existing_instance(data_dir: Path, timeout=12) -> ExistingInstance:
    deadline = time.monotonic() + timeout
    while True:
        record = read_json(data_dir / 'instance.json')
        if probe_instance(record):
            return ExistingInstance(record)
        if time.monotonic() >= deadline:
            raise LaunchError('Figure Studio 正在启动或关闭。请稍后再次打开。\n'
                              'Figure Studio is starting or closing. Try again shortly.')
        time.sleep(.15)


def make_handler(suite_root: Path):
    # All plotting code is bundled; this never shells out to an installed Python.
    for folder in ('make-sci-data-figures', 'polish-sci-figures'):
        scripts = suite_root / 'skills' / folder / 'scripts'
        if not scripts.is_dir():
            raise LaunchError('安装文件不完整 / Required application files are missing: ' + folder)
        if str(scripts) not in sys.path:
            sys.path.insert(0, str(scripts))
    from studio_server import Handler

    class DesktopHandler(Handler):
        def setup(self):
            super().setup()
            # An abandoned browser connection must not hold application exit
            # forever. This limits socket reads/writes, not the render itself.
            self.connection.settimeout(30)

        def do_GET(self):
            if urlsplit(self.path).path != '/api/desktop/health':
                return super().do_GET()
            if (self.headers.get('Host') != self.server.address or
                    self.headers.get('X-Studio-Instance') != self.server.instance_id):
                return self.send_json(403, {'error': 'Local application authorization required'})
            return self.send_json(200, {'app': APP_ID, 'instance_id': self.server.instance_id,
                                       'pid': os.getpid()})

    return DesktopHandler


class LocalServer(ThreadingHTTPServer):
    daemon_threads = False
    block_on_close = True

    def server_bind(self):
        # Windows SO_REUSEADDR can allow another listener on the same address.
        # Exclusive binding also makes the persisted-origin conflict explicit.
        if os.name == 'nt':
            import socket
            self.allow_reuse_address = False
            self.socket.setsockopt(socket.SOL_SOCKET, socket.SO_EXCLUSIVEADDRUSE, 1)
        return super().server_bind()


class RunningService:
    def __init__(self, server, lock: InstanceLock, data_dir: Path):
        self.server, self.lock, self.data_dir = server, lock, data_dir
        self.port = server.server_address[1]
        self.url = f'http://127.0.0.1:{self.port}/'
        self.thread = threading.Thread(target=server.serve_forever, kwargs={'poll_interval': .2},
                                       name='Figure Studio service', daemon=True)
        self.closed = False
        self.close_lock = threading.Lock()

    def start(self):
        self.thread.start()
        write_json(self.data_dir / 'instance.json', {'app': APP_ID, 'port': self.port,
                   'instance_id': self.server.instance_id, 'pid': os.getpid()})
        LOG.info('Service ready on 127.0.0.1:%s', self.port)
        return self

    def close(self):
        with self.close_lock:
            if self.closed:
                return
            self.closed = True
            try:
                if self.thread.is_alive():
                    self.server.shutdown()
                    self.thread.join()
                self.server.server_close()  # Wait for accepted render jobs to finish.
            finally:
                record_path = self.data_dir / 'instance.json'
                if read_json(record_path).get('instance_id') == self.server.instance_id:
                    record_path.unlink(missing_ok=True)
                self.lock.release()
            LOG.info('Service stopped')


def start_service(data_dir: Path, suite_root: Path | None = None, preferred_port=DEFAULT_PORT):
    data_dir = Path(data_dir).resolve()
    suite_root = Path(suite_root or resource_root()).resolve()
    data_dir.mkdir(parents=True, exist_ok=True)
    lock = InstanceLock(data_dir / 'instance.lock')
    if not lock.acquire():
        return existing_instance(data_dir)
    server = None
    try:
        page = prepare_workspace(data_dir, suite_root)
        handler = make_handler(suite_root)
        config_path = data_dir / 'settings.json'
        settings = read_json(config_path)
        saved_port = settings.get('port')
        if config_path.exists() and (type(saved_port) is not int or not 1024 <= saved_port <= 65535):
            raise LaunchError('本机端口设置无效。请保留工作目录并联系支持。\n'
                              'The saved local port is invalid. Keep the data directory and contact support.')
        candidates = [saved_port] if saved_port else ([0] if preferred_port == 0 else
                       range(preferred_port, min(65536, preferred_port + PORT_ATTEMPTS)))
        for port in candidates:
            try:
                server = LocalServer(('127.0.0.1', port), handler)
                break
            except OSError:
                if saved_port:
                    raise LaunchError(f'本机端口 {saved_port} 已被其他程序占用。请关闭占用程序后重试。\n'
                                      '为保留浏览器中的项目记录，本次不会更换地址。\n'
                                      f'Local port {saved_port} is in use. Close the conflicting program and retry.\n'
                                      'The editor address was preserved to keep access to your browser projects.')
        if server is None:
            raise LaunchError('没有可用的本机端口 / No available local port was found.')
        server.page = page
        server.token = secrets.token_urlsafe(32)
        server.instance_id = secrets.token_urlsafe(32)
        server.address = f'127.0.0.1:{server.server_address[1]}'
        write_json(config_path, {'app': APP_ID, 'port': server.server_address[1]})
        service = RunningService(server, lock, data_dir)
        try:
            return service.start()
        except Exception:
            service.close()
            raise
    except Exception:
        if server is not None:
            server.server_close()
        lock.release()
        raise


def self_test(service: RunningService, output_dir: Path) -> dict:
    """Use the same authorized HTTP routes as the packaged editor, not mocks."""
    output_dir.mkdir(parents=True, exist_ok=True)
    port, token = service.port, service.server.token
    checks = []
    import tkinter as tk
    shell = tk.Tk()
    try:
        shell.withdraw()
        shell.update_idletasks()
        tk_version = str(shell.tk.call('package', 'provide', 'Tk'))
        tcl_version = str(shell.tk.call('info', 'patchlevel'))
    finally:
        shell.destroy()
    checks.append('Tk desktop shell resources')

    def request(path, payload):
        status, raw = http_request(port, path, payload, token)
        value = json.loads(raw)
        if status != 200:
            raise LaunchError(f'{path}: HTTP {status}: {value.get("error", value)}')
        checks.append(path)
        return value

    status, raw = http_request(port)
    assert status == 200 and b'id="local-engine"' in raw and b'id="project"' in raw
    checks.append('GET editor')
    assert http_request(port, '/api/analyze', {})[0] == 403
    assert http_request(port, '/api/analyze', {}, token,
                        headers={'Origin': 'https://example.invalid'})[0] == 403
    assert http_request(port, '/', headers={'Host': 'example.invalid'})[0] == 403
    assert http_request(port, '/api/desktop/health')[0] == 403
    checks.append('Host / Origin / token guards')
    recipe = {'family': 'gallery', 'parameters': {'view': 'compare_box_points'},
              'font': 'Arial', 'palette': 'zhoy_muted'}
    rows = [['group', 'unit', 'value']]
    values = [-1.9, -.7, -1.2, .3, -.4, .8, .1, -.9]
    for index, group in enumerate(('Control', 'Treatment A', 'Treatment B')):
        for unit, value in enumerate(values):
            rows.append([group, f'G{index}-U{unit + 1:02}', str(value + index * 1.3 + .03 * unit * index)])
    config = {'mode': 'raw', 'group': 'group', 'value': 'value', 'unit': 'unit',
              'design': 'independent', 'method': 'welch', 'family': 'all_pairs',
              'goal': 'mean', 'design_confirmed': True, 'unit_role': 'independent_experimental_unit'}
    analysis = request('/api/analyze', {'recipe': recipe, 'rows': rows, 'config': config})
    axes = {'y_min': -3, 'y_max': 6, 'reference_lines': [
        {'axis': 'y', 'value': 0, 'style': 'dashed', 'width': .8, 'color': '#68768a'}]}
    rendered = request('/api/render', {'recipe': recipe, 'rows': rows, 'statistics': config, 'axes': axes})
    panel = rendered['panel']
    assert panel['table']['sha256'] == analysis['data_sha256'] == panel['statistics']['data_sha256']
    assert panel['statistics']['analysis'] == analysis['analysis']
    assert len(panel['statistics']['analysis']['primary_test']['pairwise']) == 3
    variant = panel['variants'][panel.get('initialVariant', 0)]
    (output_dir / 'render.svg').write_text(variant['svg'], encoding='utf-8')
    reflowed = request('/api/reflow', {'recipe': panel['recipe'], 'rows': rows,
                                     'width': 432, 'height': 288})
    variant = reflowed['variant']
    assert abs(variant['width'] - 432) < .001 and abs(variant['height'] - 288) < .001
    assert variant['axis_controls']['settings'] == axes
    (output_dir / 'reflow.svg').write_text(variant['svg'], encoding='utf-8')
    (output_dir / 'analysis.json').write_text(json.dumps(analysis, ensure_ascii=False, indent=2), encoding='utf-8')
    report = {'passed': True, 'checks': checks, 'data_sha256': analysis['data_sha256'],
              'variants': len(panel['variants']), 'url': service.url,
              'frozen': bool(getattr(sys, 'frozen', False)), 'python': sys.version,
              'tk': tk_version, 'tcl': tcl_version,
              'resources': str(resource_root())}
    write_json(output_dir / 'self-test.json', report)
    return report


def open_editor(url: str):
    if not webbrowser.open(url, new=2):
        raise LaunchError('无法打开默认浏览器。请复制地址到浏览器：\n'
                          'Could not open the default browser. Open this address:\n' + url)


def apply_window_icon(window, suite_root=None) -> bool:
    """Use the bundled brand icon without making startup depend on shell icons."""
    from tkinter import TclError
    icon = (suite_root or resource_root()) / WINDOW_ICON
    if not icon.is_file():
        LOG.warning('Window icon is missing: %s', icon)
        return False
    try:
        window.iconbitmap(default=str(icon))
        return True
    except (TclError, OSError):
        LOG.warning('Could not load the window icon', exc_info=True)
        return False


def open_official_project():
    """Called only by the explicit project button; no startup network request."""
    open_editor(OFFICIAL_PROJECT_URL)


def run_window(data_dir: Path, no_open=False) -> int:
    import tkinter as tk
    from tkinter import ttk, messagebox
    window = tk.Tk()
    window.title(WINDOW_TITLE)
    window.geometry('590x400')
    window.minsize(550, 380)
    apply_window_icon(window)
    window.configure(background='#f5f6f8')
    style = ttk.Style(window)
    if 'vista' in style.theme_names():
        style.theme_use('vista')
    style.configure('Studio.TFrame', background='#f5f6f8')
    style.configure('Studio.TLabel', background='#f5f6f8', foreground='#303944', font=('Segoe UI', 10))
    frame = ttk.Frame(window, padding=28, style='Studio.TFrame')
    frame.pack(fill='both', expand=True)
    ttk.Label(frame, text='Figure Studio', font=('Segoe UI', 21, 'bold'),
              background='#f5f6f8', foreground='#243247').pack(anchor='w')
    ttk.Label(frame, text='polish-sci-figures 官方配套编辑器\n'
              'Official companion editor for polish-sci-figures',
              style='Studio.TLabel', wraplength=475).pack(anchor='w', pady=(5, 0))
    status = tk.StringVar(value='正在启动编辑器…  /  Starting the editor…')
    ttk.Label(frame, textvariable=status, style='Studio.TLabel', wraplength=455).pack(anchor='w', pady=(16, 10))
    address = tk.StringVar(value='')
    ttk.Entry(frame, textvariable=address, state='readonly').pack(fill='x', pady=(0, 14))
    ttk.Label(frame, text='数据保存在此设备；编辑器在默认浏览器中打开。\n'
              'Your data stays on this device. The editor opens in your browser.',
              style='Studio.TLabel', wraplength=455).pack(anchor='w')
    buttons = ttk.Frame(frame, style='Studio.TFrame')
    buttons.pack(fill='x', pady=(18, 0))
    buttons.columnconfigure(0, weight=1, uniform='actions')
    buttons.columnconfigure(1, weight=1, uniform='actions')
    result = {'service': None, 'error': None, 'closing': False, 'done': False}

    def show_error(error):
        messagebox.showerror('Figure Studio', str(error), parent=window)

    def browse():
        try:
            open_editor(result['service'].url)
        except Exception as error:
            show_error(error)

    open_button = ttk.Button(buttons, text='打开编辑器 / Open editor', command=browse, state='disabled')
    open_button.grid(row=0, column=0, sticky='ew', padx=(0, 6))

    def browse_official_project():
        try:
            open_official_project()
        except Exception as error:
            show_error(error)

    def close_worker():
        try:
            service = result['service']
            if isinstance(service, RunningService):
                service.close()
        except Exception:
            LOG.exception('Service shutdown failed')
        finally:
            result['done'] = True

    def quit_app():
        if result['closing']:
            return
        result['closing'] = True
        open_button.configure(state='disabled')
        quit_button.configure(state='disabled')
        status.set('正在关闭；等待当前计算完成… / Finishing active tasks and closing…')
        if result['service'] is not None or result['error'] is not None:
            threading.Thread(target=close_worker, daemon=True).start()
        # If startup is still running, poll() closes its eventual result.

    quit_button = ttk.Button(buttons, text='关闭服务并退出 / Quit', command=quit_app)
    quit_button.grid(row=0, column=1, sticky='ew', padx=(6, 0))
    ttk.Button(buttons, text='官方项目 / Official project', command=browse_official_project).grid(
        row=1, column=0, columnspan=2, sticky='ew', pady=(10, 0))
    window.protocol('WM_DELETE_WINDOW', quit_app)
    # Account for the actual platform font/DPI before fixing the minimum size.
    # The project action has its own row, so localized button captions cannot
    # compete with the editor/quit actions for horizontal space.
    window.update_idletasks()
    needed_width = frame.winfo_reqwidth() + 16
    needed_height = frame.winfo_reqheight() + 16
    window.minsize(max(550, needed_width), max(380, needed_height))
    window.geometry(f'{max(590, needed_width)}x{max(400, needed_height)}')

    def start_worker():
        try:
            result['service'] = start_service(data_dir)
        except Exception as error:
            result['error'] = error
            LOG.exception('Startup failed')

    startup = threading.Thread(target=start_worker, daemon=True, name='Figure Studio startup')
    startup.start()
    ready = False

    def poll():
        nonlocal ready
        if result['done']:
            window.destroy()
            return
        if not ready and not startup.is_alive():
            ready = True
            if result['closing']:
                threading.Thread(target=close_worker, daemon=True).start()
            elif result['error'] is not None:
                status.set('无法启动 / Unable to start')
                show_error(result['error'])
            else:
                service = result['service']
                address.set(service.url)
                if isinstance(service, ExistingInstance):
                    if not no_open:
                        browse()
                    window.destroy()
                    return
                status.set('编辑器已就绪 / Editor is ready')
                open_button.configure(state='normal')
                if not no_open:
                    browse()
        window.after(100, poll)

    window.after(50, poll)
    window.mainloop()
    return 1 if result['error'] else 0


def main(argv=None):
    parser = argparse.ArgumentParser(description='Figure Studio desktop application')
    parser.add_argument('--data-dir', type=Path, help='Isolated application data directory')
    parser.add_argument('--self-test', action='store_true', help='Run real HTTP checks without opening any UI')
    parser.add_argument('--output-dir', type=Path, help='Self-test report and SVG output directory')
    parser.add_argument('--no-open', action='store_true', help='Do not automatically open the default browser')
    args = parser.parse_args(argv)
    data_dir = (args.data_dir or (default_data_dir() / 'self-test' if args.self_test else default_data_dir())).resolve()
    output_dir = (args.output_dir or data_dir / 'self-test-output').resolve()
    service = None
    try:
        prepare_runtime(data_dir)
        if args.self_test:
            service = start_service(data_dir)
            if not isinstance(service, RunningService):
                raise LaunchError('Self-test requires a data directory not used by a running editor.')
            report = self_test(service, output_dir)
            print(json.dumps(report, ensure_ascii=False))
            return 0
        return run_window(data_dir, args.no_open)
    except Exception as error:
        LOG.exception('Application failed')
        if args.self_test:
            write_json(output_dir / 'self-test.json', {'passed': False, 'error': str(error),
                       'frozen': bool(getattr(sys, 'frozen', False))})
            if sys.stderr:
                print(str(error), file=sys.stderr)
        else:
            try:
                import tkinter.messagebox
                tkinter.messagebox.showerror('Figure Studio', str(error))
            except Exception:
                pass
        return 1
    finally:
        if isinstance(service, RunningService):
            service.close()


if __name__ == '__main__':
    raise SystemExit(main())
