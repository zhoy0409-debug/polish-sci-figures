"""Windowed, self-contained Figure Studio launcher and loopback service.

PyInstaller places the bundled application in ``sys._MEIPASS / 'suite'``.
The editable workspace, local runtime descriptor and port live in the user's
data directory. No external Python executable or shell process is launched.
"""
